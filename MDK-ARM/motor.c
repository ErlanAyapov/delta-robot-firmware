// ??? ???????? ????? ?????????? "??????" ??? Toggle Mode
static const uint16_t delta_CH1 = 10000; // ????????, 50 ?? (?????? 10 ?? ????????????)
static const uint16_t delta_CH2 =  5000; // ????????, 100 ?? (?????? 5 ?? ????????????)

/**
  * @brief ????????????? ?????????: ???????? ????????? CCR ? ??????? ???????.
  *        ???? ?? ????????? ??????.
  */
static void Motor_Prepare(void)
{
    // ?????????? ?????? ????? ??????????????
    HAL_TIM_OC_Stop_IT(&htim8, TIM_CHANNEL_1);
    HAL_TIM_OC_Stop_IT(&htim8, TIM_CHANNEL_2);

    // ?????? ????????? Compare ??? CH1 ? CH2
    __HAL_TIM_SET_COMPARE(&htim8, TIM_CHANNEL_1, delta_CH1);
    __HAL_TIM_SET_COMPARE(&htim8, TIM_CHANNEL_2, delta_CH2);

    // ???????? ???????, ????? ??? ?????? «??????????» ????????? ? ????
    __HAL_TIM_SET_COUNTER(&htim8, 0);
}

/**
  * @brief ?????? ????????? Toggle ?? TIM8_CH1 ? CH2 ? ??????? «????????».
  */
void Motor_StartPWM(void)
{
    Motor_Prepare();

    // ????????? ?????? ? ?????? Output Compare + ??????????
    // (??????????????, ??? ? CubeMX ????????? OCMode = Toggle)
    HAL_TIM_OC_Start_IT(&htim8, TIM_CHANNEL_1);
    HAL_TIM_OC_Start_IT(&htim8, TIM_CHANNEL_2);
}

/**
  * @brief ?????????? ????????? ?? ????? ???????.
  */
void Motor_StopPWM(void)
{
    HAL_TIM_OC_Stop_IT(&htim8, TIM_CHANNEL_1);
    HAL_TIM_OC_Stop_IT(&htim8, TIM_CHANNEL_2);
}

/**
  * @brief ?????? ??? ?????????? CCR «?? ????».
  *        ?????????? ?? HAL_TIM_OC_DelayElapsedCallback ? main.c
  */
void Motor_UpdateCompare(TIM_HandleTypeDef *htim)
{
    // ????????, ??? ??? ????????????? TIM8
    if (htim->Instance == TIM8)
    {
        // ????? ????? ????????? ???????????
        if (htim->Channel == HAL_TIM_ACTIVE_CHANNEL_1)
        {
            // ???????? CCR1 ?????? ?? delta_CH1
            __HAL_TIM_SET_COMPARE(htim, TIM_CHANNEL_1,
               __HAL_TIM_GET_COMPARE(htim, TIM_CHANNEL_1) + delta_CH1
            );
        }
        else if (htim->Channel == HAL_TIM_ACTIVE_CHANNEL_2)
        {
            // ???????? CCR2 ?????? ?? delta_CH2
            __HAL_TIM_SET_COMPARE(htim, TIM_CHANNEL_2,
               __HAL_TIM_GET_COMPARE(htim, TIM_CHANNEL_2) + delta_CH2
            );
        }
    }
}
